code("""
from transformers import AutoModelForCausalLM, AutoTokenizer

tok = AutoTokenizer.from_pretrained(BASE_MODEL)
tok.padding_side = "left"          # left padding -> the LAST position is always "the next token"
model = AutoModelForCausalLM.from_pretrained(BASE_MODEL, dtype=DTYPE).to(DEVICE)

# Qwen's tokenizer has one token per digit; we score by comparing these 5 logits.
DIGIT_IDS = [tok.encode(str(d), add_special_tokens=False) for d in range(1, 6)]
assert all(len(t) == 1 for t in DIGIT_IDS), DIGIT_IDS
DIGIT_IDS = [t[0] for t in DIGIT_IDS]
print("params:", sum(p.numel() for p in model.parameters()) / 1e6, "M")
""")

code("""
def prompt_text(q, a):
    return tok.apply_chat_template(build_messages(q, a), tokenize=False, add_generation_prompt=True)

@torch.no_grad()
def score(model, df, batch_size=16):
    \"\"\"Returns (predicted class 1-5, expected score) from next-token logits of '1'..'5'.\"\"\"
    model.eval()
    prompts = [prompt_text(q, a) for q, a in zip(df.question, df.answer)]
    preds, expected = [], []
    for i in range(0, len(prompts), batch_size):
        enc = tok(prompts[i:i + batch_size], return_tensors="pt", padding=True).to(DEVICE)
        logits = model(**enc).logits[:, -1, :]               # next-token distribution
        p = logits[:, DIGIT_IDS].float().softmax(-1).cpu().numpy()
        preds += (p.argmax(1) + 1).tolist()
        expected += (p @ np.arange(1, 6)).tolist()
    return np.array(preds), np.array(expected)

def evaluate(y_true, y_pred):
    \"\"\"Same metrics as ml/classic/metrics.py.\"\"\"
    from sklearn.metrics import accuracy_score, cohen_kappa_score, f1_score, mean_absolute_error
    y_true = np.asarray(y_true, int); y_pred = np.clip(np.rint(y_pred), 1, 5).astype(int)
    return {
        "accuracy": round(float(accuracy_score(y_true, y_pred)), 3),
        "macro_f1": round(float(f1_score(y_true, y_pred, average="macro", labels=[1, 2, 3, 4, 5], zero_division=0)), 3),
        "mae": round(float(mean_absolute_error(y_true, y_pred)), 3),
        "within_1": round(float(np.mean(np.abs(y_true - y_pred) <= 1)), 3),
        "qwk": round(float(cohen_kappa_score(y_true, y_pred, weights="quadratic", labels=[1, 2, 3, 4, 5])), 3),
        "n": int(len(y_true)),
    }

t0 = time.time()
base_pred, _ = score(model, test)
base_metrics = evaluate(test.label, base_pred)
print("BASE zero-shot:", base_metrics, f"({time.time() - t0:.0f}s)")
""")

md("""
## LoRA in one paragraph
Full fine-tuning updates all 494M weights (needs lots of GPU memory). **LoRA** freezes them and adds,
next to each chosen weight matrix `W` (d×d), two small matrices `A` (d×r) and `B` (r×d) with r=16.
The layer computes `W·x + (alpha/r)·B·A·x`. Only A and B are trained (~1% of parameters), `B` starts
at zero so training starts exactly from the base model, and afterwards `B·A` can be **merged** into `W`
— zero extra inference cost.
""")

code("""
from peft import LoraConfig, get_peft_model, get_peft_model_state_dict, set_peft_model_state_dict

lora_cfg = LoraConfig(
    r=16, lora_alpha=32, lora_dropout=0.05, task_type="CAUSAL_LM",
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
)
model = get_peft_model(model, lora_cfg)      # adapters are created in float32 for stable training
model.print_trainable_parameters()
""")

code("""
# Completion-only training: the loss is computed ONLY on the answer tokens ("4<|im_end|>"),
# not on the prompt (label -100 = ignored), so the model learns to score, not to copy prompts.
def encode(q, a, label):
    p_ids = tok(prompt_text(q, a), add_special_tokens=False)["input_ids"]
    t_ids = tok(f"{label}<|im_end|>", add_special_tokens=False)["input_ids"]
    return {"input_ids": p_ids + t_ids, "labels": [-100] * len(p_ids) + t_ids}

def collate(batch):
    n = max(len(b["input_ids"]) for b in batch)
    pad = tok.pad_token_id
    ids = torch.tensor([b["input_ids"] + [pad] * (n - len(b["input_ids"])) for b in batch])
    labels = torch.tensor([b["labels"] + [-100] * (n - len(b["labels"])) for b in batch])
    mask = torch.tensor([[1] * len(b["input_ids"]) + [0] * (n - len(b["input_ids"])) for b in batch])
    return {"input_ids": ids.to(DEVICE), "labels": labels.to(DEVICE), "attention_mask": mask.to(DEVICE)}

train_ex = [encode(q, a, l) for q, a, l in zip(train.question, train.answer, train.label)]
val_ex = [encode(q, a, l) for q, a, l in zip(val.question, val.answer, val.label)]
print("max tokens:", max(len(e["input_ids"]) for e in train_ex))
""")

code("""
opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=LR, weight_decay=0.0)
steps_per_epoch = math.ceil(len(train_ex) / (BATCH_SIZE * GRAD_ACCUM))
total = steps_per_epoch * EPOCHS
warmup = max(1, int(0.06 * total))
sched = torch.optim.lr_scheduler.LambdaLR(opt, lambda s: min(1.0, (s + 1) / warmup) * max(0.0, (total - s) / max(1, total - warmup)))
use_amp = DEVICE == "cuda"
scaler = torch.amp.GradScaler("cuda", enabled=use_amp)

@torch.no_grad()
def val_loss():
    model.eval(); losses = []
    for i in range(0, len(val_ex), BATCH_SIZE):
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=use_amp):
            losses.append(model(**collate(val_ex[i:i + BATCH_SIZE])).loss.item())
    return float(np.mean(losses))

best, best_state, t0 = float("inf"), None, time.time()
for epoch in range(EPOCHS):
    model.train(); random.shuffle(train_ex)
    for step, i in enumerate(range(0, len(train_ex), BATCH_SIZE)):
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=use_amp):
            loss = model(**collate(train_ex[i:i + BATCH_SIZE])).loss / GRAD_ACCUM
        scaler.scale(loss).backward()
        if (step + 1) % GRAD_ACCUM == 0 or i + BATCH_SIZE >= len(train_ex):
            scaler.step(opt); scaler.update(); opt.zero_grad(); sched.step()
    vl = val_loss()
    print(f"epoch {epoch + 1}: val_loss={vl:.4f} ({(time.time() - t0) / 60:.1f} min)")
    if vl < best:                                   # keep the best adapter (early stopping)
        best, best_state = vl, copy.deepcopy(get_peft_model_state_dict(model))
set_peft_model_state_dict(model, best_state)
train_minutes = round((time.time() - t0) / 60, 1)
""")

